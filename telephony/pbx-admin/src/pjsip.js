/**
 * Renders the generated PJSIP include file consumed by Asterisk
 * (`pjsip.conf` contains `#include pjsip.d/*.conf`).
 *
 * Each extension becomes an endpoint + aor + auth triple. The base file
 * provides the `webrtc-endpoint`, `aor-template` and `auth-template` templates.
 */
import { randomBytes } from "node:crypto";

const NUMBER_RE = /^[0-9]{2,12}$/;

export function isValidNumber(number) {
  return typeof number === "string" && NUMBER_RE.test(number);
}

/** A SIP secret: 32 bytes of base64url, URL-safe and digest friendly. */
export function generateSipPassword() {
  return randomBytes(32).toString("base64url");
}

/** Remove characters that could break the generated include file. */
export function sanitiseDisplayName(name) {
  return String(name || "")
    .replace(/[\r\n"\\]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 120);
}

/**
 * @param {Array<{number:string, displayName?:string, password:string, enabled?:boolean, context?:string}>} extensions
 * @returns {string} the include file contents
 */
export function renderPjsipInclude(extensions, { context = "cloudtel-internal" } = {}) {
  const lines = [
    "; Generated by CloudTel pbx-admin — do not edit by hand.",
    "; Source of truth: CloudTel API -> PBX admin /extensions.",
    "",
  ];
  const seen = new Set();
  for (const ext of [...extensions].sort((a, b) => a.number.localeCompare(b.number))) {
    if (!ext || !isValidNumber(ext.number)) continue;
    if (seen.has(ext.number)) continue;
    seen.add(ext.number);
    if (ext.enabled === false) continue;
    const displayName = sanitiseDisplayName(ext.displayName) || `Extension ${ext.number}`;
    lines.push(
      `[${ext.number}](webrtc-endpoint)`,
      `auth = auth${ext.number}`,
      `aors = ${ext.number}`,
      `callerid = "${displayName}" <${ext.number}>`,
      `context = ${ext.context || context}`,
      "",
      `[${ext.number}](aor-template)`,
      "",
      `[auth${ext.number}](auth-template)`,
      `username = ${ext.number}`,
      `password = ${ext.password}`,
      ""
    );
  }
  return lines.join("\n");
}
